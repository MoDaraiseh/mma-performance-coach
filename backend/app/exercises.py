def available_equipment(profile):
    # Old profiles keep their explicit legacy assumptions; new profiles can specify each item.
    if profile.equipment is not None:
        return set(profile.equipment)
    return ({"dumbbells", "bench"} if profile.gym else set()) | (
        {"mats"} if profile.mma_gym else set()
    )


def alternatives(key, profile):
    have = available_equipment(profile)
    return [
        deepcopy(CATALOG[k])
        for k in CATALOG[key]["alternatives"]
        if set(CATALOG[k]["equipment"]) <= have and not CATALOG[k]["requires_coach"]
    ]


